// 2026-11-23 設定 › 啟動與更新「啟動遊戲時自動開啟」的純邏輯(不 import electron;main.ts 注入 fs / shell.writeShortcutLink / spawn)。
//
// 本程式沒開時就沒辦法自己偵測遊戲 → 勾選時安裝一個登入時啟動的輕量背景監看:
//   userData/game-autolaunch/watch-game.ps1   每 5 秒看一次遊戲行程,「沒開 → 開」那一刻本程式沒在跑才啟動(遊戲中手動關掉不會再被打開)
//   userData/game-autolaunch/start-hidden.vbs 用 wscript 隱藏視窗啟動上面的 PowerShell(直接捷徑到 powershell 會閃一下主控台)
//   啟動資料夾/<STARTUP_LINK_NAME>             Windows 登入時跑 start-hidden.vbs
// 取消勾選 = 刪掉捷徑與兩個檔;監看每輪檢查捷徑還在不在,不在就自己結束(不用找行程砍)。
// 監看腳本內容改了(例如可攜版搬了位置)→ 舊監看偵測到檔案時間變了就結束,新監看等 mutex(最多 15 秒)接手。
import path from 'node:path'

export const WATCHER_DIR_NAME = 'game-autolaunch'
export const WATCHER_SCRIPT_NAME = 'watch-game.ps1'
export const WATCHER_LAUNCHER_NAME = 'start-hidden.vbs'
export const STARTUP_LINK_NAME = 'ExileAppraiser GameAutoLaunch.lnk'
export const WATCHER_MUTEX = 'Local\\ExileAppraiserGameAutoLaunch'
export const WATCHER_INTERVAL_SEC = 5

/** PoE1 / PoE2 各平台的遊戲行程名(不含 .exe;兩代的 Steam 版都叫 PathOfExileSteam) */
export const GAME_PROCESS_NAMES: readonly string[] = [
  'PathOfExile', 'PathOfExile_x64',
  'PathOfExileSteam', 'PathOfExile_x64Steam',
  'PathOfExile_KG', 'PathOfExile_x64_KG',
  'PathOfExileEGS', 'PathOfExile_x64EGS'
]

/** PowerShell 單引號字串:單引號寫兩次 */
function psQuote (s: string): string {
  return `'${s.replace(/'/g, "''")}'`
}

/** 要啟動的 exe:可攜版每次啟動都解壓到暫存目錄,execPath 下次就不在了 → 指向可攜 exe 本體 */
export function launchTarget (env: Record<string, string | undefined>, execPath: string): string {
  return env.PORTABLE_EXECUTABLE_FILE || execPath
}

export interface WatcherPaths {
  dir: string
  script: string
  launcher: string
  link: string
}

export function watcherPaths (userDataDir: string, startupDir: string): WatcherPaths {
  const dir = path.win32.join(userDataDir, WATCHER_DIR_NAME)
  return {
    dir,
    script: path.win32.join(dir, WATCHER_SCRIPT_NAME),
    launcher: path.win32.join(dir, WATCHER_LAUNCHER_NAME),
    link: path.win32.join(startupDir, STARTUP_LINK_NAME)
  }
}

/**
 * 監看腳本。appExe = 要啟動的 exe;appProcessNames = 「本程式已在跑」要認的行程名(安裝版 = ExileAppraiser;
 * 可攜版另認外層 exe 的名字)。存檔時要加 UTF-8 BOM(Windows PowerShell 5.1 讀沒 BOM 的檔當 ANSI,路徑有中文會壞)。
 */
export function watcherScript (opts: { appExe: string, appProcessNames: readonly string[], linkPath: string }): string {
  const list = (xs: readonly string[]) => `@(${xs.map(psQuote).join(', ')})`
  return [
    '# ExileAppraiser: start the app when Path of Exile starts.',
    '# Generated by ExileAppraiser (Settings > Startup > Open with the game). Do not edit; toggle the setting instead.',
    `$AppPath   = ${psQuote(opts.appExe)}`,
    `$AppNames  = ${list(opts.appProcessNames)}`,
    `$LinkPath  = ${psQuote(opts.linkPath)}`,
    `$GameNames = ${list(GAME_PROCESS_NAMES)}`,
    '',
    '# One watcher at a time. A newer watcher waits for the old one to notice its script changed and quit.',
    `$mutex = New-Object System.Threading.Mutex($false, ${psQuote(WATCHER_MUTEX)})`,
    '$owned = $false',
    'try { $owned = $mutex.WaitOne(15000) } catch [System.Threading.AbandonedMutexException] { $owned = $true }',
    'if (-not $owned) { exit }',
    '',
    '$stamp = (Get-Item -LiteralPath $PSCommandPath).LastWriteTimeUtc',
    '$gameWasRunning = $false',
    '# The setting was turned off (shortcut removed) or this script was rewritten -> quit.',
    'while ((Test-Path -LiteralPath $LinkPath) -and (Test-Path -LiteralPath $PSCommandPath) -and ((Get-Item -LiteralPath $PSCommandPath).LastWriteTimeUtc -eq $stamp)) {',
    '    $gameRunning = [bool](Get-Process -Name $GameNames -ErrorAction SilentlyContinue)',
    '    # Only on the not-running -> running edge, so closing the app mid-session does not reopen it.',
    '    if ($gameRunning -and -not $gameWasRunning) {',
    '        $appRunning = [bool](Get-Process -Name $AppNames -ErrorAction SilentlyContinue)',
    '        if (-not $appRunning -and (Test-Path -LiteralPath $AppPath)) {',
    '            Start-Process -FilePath $AppPath -WorkingDirectory (Split-Path -LiteralPath $AppPath)',
    '        }',
    '    }',
    '    $gameWasRunning = $gameRunning',
    `    Start-Sleep -Seconds ${WATCHER_INTERVAL_SEC}`,
    '}',
    '$mutex.ReleaseMutex()',
    ''
  ].join('\r\n')
}

/** 隱藏視窗啟動監看。內容只有 ASCII(路徑從自己的位置推),WSH 讀 ANSI 也不會壞。 */
export function launcherScript (): string {
  return [
    'Set sh = CreateObject("WScript.Shell")',
    'dir = CreateObject("Scripting.FileSystemObject").GetParentFolderName(WScript.ScriptFullName)',
    `sh.Run "powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File """ & dir & "\\${WATCHER_SCRIPT_NAME}""", 0, False`,
    ''
  ].join('\r\n')
}

export interface GameAutoLaunchDeps {
  isPackaged: boolean
  env: Record<string, string | undefined>
  execPath: string
  userDataDir: string
  /** 使用者的「啟動」資料夾(%APPDATA%\Microsoft\Windows\Start Menu\Programs\Startup) */
  startupDir: string
  /** %SystemRoot%(找 wscript.exe) */
  systemRoot: string
  exists: (p: string) => boolean
  readFile: (p: string) => Buffer | null
  writeFile: (p: string, data: Buffer) => void
  mkdir: (p: string) => void
  remove: (p: string) => void
  /** = Electron shell.writeShortcutLink;回 false 或丟例外都算失敗 */
  writeShortcut: (p: string, operation: 'create' | 'replace', options: { target: string, args: string, cwd: string, description: string }) => boolean
  /** 分離啟動、不等它結束 */
  spawnDetached: (exe: string, args: string[]) => void
}

export type GameAutoLaunchResult =
  | { ok: true, action: 'installed', link: string }
  | { ok: true, action: 'removed' | 'none' }
  | { ok: false, reason: 'dev' | 'failed' }

const UTF8_BOM = Buffer.from([0xef, 0xbb, 0xbf])

/** 內容不同才寫(回傳有沒有寫) */
function writeIfChanged (deps: GameAutoLaunchDeps, file: string, data: Buffer): boolean {
  const old = deps.readFile(file)
  if (old != null && old.equals(data)) return false
  deps.writeFile(file, data)
  return true
}

export function applyGameAutoLaunch (enabled: boolean, deps: GameAutoLaunchDeps): GameAutoLaunchResult {
  const p = watcherPaths(deps.userDataDir, deps.startupDir)
  if (!enabled) {
    try {
      let any = false
      for (const f of [p.link, p.script, p.launcher]) {
        if (deps.exists(f)) { deps.remove(f); any = true }
      }
      return { ok: true, action: any ? 'removed' : 'none' }
    } catch (e) {
      console.warn('[game-autolaunch] 移除失敗', e)
      return { ok: false, reason: 'failed' }
    }
  }
  // 開發模式的 execPath 是 electron.exe,啟動起來不是這支程式
  if (!deps.isPackaged) return { ok: false, reason: 'dev' }
  const appExe = launchTarget(deps.env, deps.execPath)
  const names = [...new Set([path.win32.basename(deps.execPath, '.exe'), path.win32.basename(appExe, '.exe')])]
  try {
    deps.mkdir(p.dir)
    const script = Buffer.concat([UTF8_BOM, Buffer.from(watcherScript({ appExe, appProcessNames: names, linkPath: p.link }), 'utf8')])
    writeIfChanged(deps, p.script, script)
    writeIfChanged(deps, p.launcher, Buffer.from(launcherScript(), 'ascii'))
    const wscript = path.win32.join(deps.systemRoot, 'System32', 'wscript.exe')
    const ok = deps.writeShortcut(p.link, deps.exists(p.link) ? 'replace' : 'create', {
      target: wscript, args: `"${p.launcher}"`, cwd: p.dir, description: 'ExileAppraiser: open with the game'
    })
    if (!ok) return { ok: false, reason: 'failed' }
    // 現在就啟動,不用等下次登入(已有監看在跑 → 新的拿不到 mutex 就結束)
    deps.spawnDetached(wscript, [p.launcher])
    return { ok: true, action: 'installed', link: p.link }
  } catch (e) {
    console.warn('[game-autolaunch] 安裝失敗', e)
    return { ok: false, reason: 'failed' }
  }
}
